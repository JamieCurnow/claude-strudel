// Generates the reference material Claude sees in its system prompt:
//   worker/prompt/generated/reference.md  - every Strudel function, one line each (from @strudel/reference)
//   worker/prompt/generated/sounds.md     - every sound name the app loads (from the sample maps in shared/sound-banks.ts)
//   worker/prompt/generated/sounds.json   - the same names as a flat list (used by tests to validate examples)
//
// Run with `npm run reference` after bumping Strudel or changing SOUND_BANKS. Output is committed.
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { reference } from '@strudel/reference'
import { DRUM_MACHINE_ALIASES, SOUND_BANKS, SYNTH_SOUNDS } from '../shared/sound-banks.ts'

const OUT = new URL('../worker/prompt/generated/', import.meta.url)

const stripHtml = (html = '') =>
  html
    .replace(/<\/p>\s*<p>/g, ' ')
    .replace(/<br\s*\/?>/g, ' ')
    .replace(/<[^>]+>/g, '')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&amp;/g, '&')
    .replace(/\s+/g, ' ')
    .trim()

const shorten = (text, max = 220) => {
  if (text.length <= max) return text
  const cut = text.slice(0, max)
  const stop = cut.lastIndexOf('. ')
  return (stop > 80 ? cut.slice(0, stop + 1) : cut.trimEnd() + '…').trim()
}

const SECTION_NAMES = {
  'controls.mjs': 'Controls (sound + effect parameters)',
  'pattern.mjs': 'Pattern functions',
  'signal.mjs': 'Signals + randomness',
  'pick.mjs': 'Pick / inhabit',
  'euclid.mjs': 'Euclidean rhythms',
  'repl.mjs': 'Globals',
  'tonal.mjs': 'Tonal (notes, scales, chords)',
  'voicings.mjs': 'Chord voicings',
  'mini.mjs': 'Mini-notation',
  'util.mjs': 'Utilities',
  'sampler.mjs': 'Sampler',
  'superdough.mjs': 'Synths + output',
  'wavetable.mjs': 'Wavetables',
  'reverbGen.mjs': 'Reverb'
}

// Editor widgets, visualisers (the app draws its own), MIDI/OSC/motion I/O and internals: not for Claude.
const EXCLUDE_FILES = new Set([
  'codemirror.mjs',
  'slider.mjs',
  'drawLine.mjs',
  'midi.mjs',
  'motion.mjs',
  'osc.mjs',
  'ola-processor.js',
  'worklets.mjs',
  'dough.mjs',
  'pianoroll.mjs',
  'pitchwheel.mjs',
  'spiral.mjs',
  'scope.mjs',
  'spectrum.mjs',
  'index.mjs'
])

const buildReference = () => {
  const docs = reference.docs.filter((doc) => {
    const tags = (doc.tags ?? []).map((tag) => tag.title)
    const excluded = EXCLUDE_FILES.has(doc.meta?.filename)
    return doc.name && !excluded && !tags.includes('superdirtonly') && !doc.name.startsWith('_')
  })
  const seen = new Set()
  const sections = new Map()
  for (const doc of docs) {
    if (seen.has(doc.name)) continue
    seen.add(doc.name)
    const params = (doc.params ?? [])
      .map((p) => `${p.name}${p.type ? ':' + p.type.names.join('|') : ''}`)
      .join(', ')
    const aka = doc.synonyms?.length ? ` (aka ${doc.synonyms.join(', ')})` : ''
    const description = shorten(stripHtml(doc.description))
    const example = doc.examples?.[0]?.split('\n').filter(Boolean).join(' ').slice(0, 160)
    const line = `- ${doc.name}(${params})${aka}: ${description}${example ? ` e.g. \`${example}\`` : ''}`
    const file = doc.meta?.filename ?? 'other'
    const title = SECTION_NAMES[file] ?? `Other (${file.replace(/\.mjs$/, '')})`
    if (!sections.has(title)) sections.set(title, [])
    sections.get(title).push(line)
  }
  const ordered = [...sections.entries()].sort(([a], [b]) => {
    const order = Object.values(SECTION_NAMES)
    return (order.indexOf(a) + 1 || 99) - (order.indexOf(b) + 1 || 99)
  })
  const body = ordered.map(([title, lines]) => `### ${title}\n\n${lines.join('\n')}`).join('\n\n')
  return `<!-- generated by scripts/build-reference.mjs from @strudel/reference - do not edit -->\n\n${body}\n`
}

const resolveMapUrl = (map) => {
  if (!map.startsWith('github:')) return map
  const [user, repo, branch = 'main'] = map.slice('github:'.length).split('/')
  return `https://raw.githubusercontent.com/${user}/${repo}/${branch}/strudel.json`
}

const fetchJson = async (url) => {
  const res = await fetch(url)
  if (!res.ok) throw new Error(`${url}: ${res.status}`)
  return res.json()
}

const soundfontNames = async () => {
  const source = await readFile(
    new URL('../node_modules/@strudel/soundfonts/gm.mjs', import.meta.url),
    'utf8'
  )
  return [...source.matchAll(/^\s{2}(gm_[a-z0-9_]+):/gm)].map((m) => m[1])
}

const buildSounds = async () => {
  const all = new Set(SYNTH_SOUNDS)
  const sections = []
  for (const bank of SOUND_BANKS) {
    const map = await fetchJson(resolveMapUrl(bank.map))
    const names = Object.keys(map).filter((key) => !key.startsWith('_'))
    names.forEach((name) => all.add(name.toLowerCase()))
    const count = (name) =>
      Array.isArray(map[name]) ? map[name].length : Object.keys(map[name] ?? {}).length
    if (bank.tag === 'drum-machines' && names.some((n) => n.includes('_'))) {
      const machines = new Map()
      for (const name of names) {
        const [machine, sound] = name.split('_')
        if (!sound) continue
        if (!machines.has(machine)) machines.set(machine, [])
        machines.get(machine).push(sound)
      }
      const lines = [...machines.entries()].map(([machine, sounds]) => `- ${machine}: ${sounds.join(' ')}`)
      sections.push(
        `### ${bank.id}\n${bank.about}\nUse as \`s("bd sd").bank("RolandTR909")\`.\n\n${lines.join('\n')}`
      )
    } else {
      const list = names.map((name) => `${name}(${count(name)})`).join(' ')
      sections.push(
        `### ${bank.id}\n${bank.about}\nName(number of variations, pick with .n() or "name:3"):\n\n${list}`
      )
    }
  }
  const aliases = await fetchJson(DRUM_MACHINE_ALIASES)
  const aliasLines = Object.entries(aliases)
    .map(([bank, alias]) => `${bank}=${alias}`)
    .join(', ')
  // Aliased bank keys are valid too (e.g. tr909_bd).
  for (const name of Array.from(all)) {
    const [bank, sound] = name.split('_')
    if (!sound) continue
    const alias = Object.entries(aliases).find(([b]) => b.toLowerCase() === bank)?.[1]
    for (const a of [alias].flat().filter(Boolean)) all.add(`${a}_${sound}`.toLowerCase())
  }
  const gm = await soundfontNames()
  gm.forEach((name) => all.add(name))
  const text = [
    '<!-- generated by scripts/build-reference.mjs - do not edit -->',
    `### Synths (no samples)\n${SYNTH_SOUNDS.join(' ')}. Pitch them with note()/n(). Noise: white pink brown crackle.`,
    ...sections,
    `### Drum machine bank aliases\nShort names also work in .bank(): ${aliasLines}`,
    `### General MIDI soundfonts\nPitched instruments, e.g. note("c3 e3").s("gm_epiano1"):\n\n${gm.join(' ')}`
  ].join('\n\n')
  return { text: `${text}\n`, names: [...all].sort() }
}

await mkdir(OUT, { recursive: true })
const referenceMd = buildReference()
const sounds = await buildSounds()
await writeFile(new URL('reference.md', OUT), referenceMd)
await writeFile(new URL('sounds.md', OUT), sounds.text)
await writeFile(new URL('sounds.json', OUT), JSON.stringify(sounds.names) + '\n')
console.log({
  referenceChars: referenceMd.length,
  soundsChars: sounds.text.length,
  soundNames: sounds.names.length
})
